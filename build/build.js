// ---------- 공통 유틸 ----------
function walk(obj, fn) {
  for (const k of Object.keys(obj)) {
    if (typeof obj[k] === 'string') obj[k] = fn(obj[k], k);
    else if (obj[k] && typeof obj[k] === 'object') walk(obj[k], fn);
  }
}
function rep(n, from, to) {
  let hits = 0;
  walk(day(n), s => { const c = s.split(from).length - 1; hits += c; return c ? s.split(from).join(to) : s; });
  if (!hits) fails.push(`D${n}: 찾지 못함 → ${from.slice(0, 60)}`);
  return hits;
}
